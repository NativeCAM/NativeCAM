import Foundation

/// Reads SVG files into flattened polylines in millimetres, Y up.
///
/// Supported: path (full `d` grammar), rect (rounded), circle, ellipse, line, polyline, polygon, g, a,
/// nested svg, use (of elements and symbols), transforms (matrix/translate/scale/rotate/skewX/skewY).
/// Physical size comes from the root width/height units together with the viewBox; without units,
/// 96 user units per inch (72 for files written by Adobe Illustrator, which uses 1 px = 1 pt).
/// The drawing is flipped about the document height so it stays in the positive quadrant.
public enum SVGImporter {
    /// - Parameters:
    ///   - tolerance: maximum chord deviation (mm) when flattening curves.
    ///   - pixelsPerInch: physical size of a unitless/px root length. `nil` = 96, or 72 when the file
    ///     says it was generated by Adobe Illustrator.
    public static func importSVG(data: Data, tolerance: Double = 0.01, pixelsPerInch: Double? = nil) throws -> ImportResult {
        let tol = tolerance > 0 ? tolerance : 0.01
        let tree = try SVGTreeBuilder.parse(data)
        guard let root = tree.root, root.name == "svg" else {
            throw VectorImportError.malformed("the root element is not <svg>")
        }
        var warnings: [String] = []
        if let partial = tree.partialParseError {
            warnings.append("The SVG is damaged (\(partial)); only the part before the error was imported.")
        }

        let illustrator = tree.comments.contains { $0.contains("Adobe Illustrator") }
        let ppi = pixelsPerInch.flatMap { $0 > 0 && $0.isFinite ? $0 : nil } ?? (illustrator ? 72 : 96)
        let mmPerPx = 25.4 / ppi

        // Root viewport size in mm.
        let wAttr = SVGLength.parse(root["width"])
        let hAttr = SVGLength.parse(root["height"])
        func rootMM(_ l: SVGLength?) -> Double? {
            guard let l, l.value > 0 else { return nil }
            switch l.unit {
            case "%": return nil
            case "", "px": return l.value * mmPerPx
            default: return l.value * SVGLength.cssPixels(l.unit) * 25.4 / 96
            }
        }
        var wMM = rootMM(wAttr)
        var hMM = rootMM(hAttr)
        let declaredUnit = [wAttr?.unit, hAttr?.unit].compactMap { $0 }.first { !$0.isEmpty && $0 != "px" && $0 != "%" }
        var sourceUnits: LengthUnit?
        switch declaredUnit {
        case "mm", "cm": sourceUnits = .mm
        case "in", "pt", "pc": sourceUnits = .inch
        default: sourceUnits = nil
        }
        if declaredUnit == nil || declaredUnit == "em" || declaredUnit == "ex" {
            if illustrator && pixelsPerInch == nil {
                warnings.append("No physical units on the root <svg>; file is from Adobe Illustrator, so 72 px per inch is assumed.")
            } else {
                warnings.append("No physical units on the root <svg>; assuming \(SVGNumber.format(ppi)) px per inch.")
            }
        }

        let viewBox = SVGViewBox.parse(root["viewBox"])
        if root["viewBox"] != nil && viewBox == nil {
            warnings.append("Ignored an invalid viewBox “\(root["viewBox"]!)”.")
        }
        let rootCTM: Transform2D
        let viewport: (w: Double, h: Double)
        if let vb = viewBox {
            switch (wMM, hMM) {
            case (nil, nil): wMM = vb.w * mmPerPx; hMM = vb.h * mmPerPx
            case let (nil, h?): wMM = h * vb.w / vb.h
            case let (w?, nil): hMM = w * vb.h / vb.w
            default: break
            }
            rootCTM = vb.transform(toWidth: wMM!, height: hMM!, preserveAspectRatio: root["preserveAspectRatio"])
            viewport = (vb.w, vb.h)
        } else {
            // Without a viewBox, user units are CSS px; only a unitless/px root size uses the px-per-inch guess.
            let userMM = declaredUnit == nil ? mmPerPx : 25.4 / 96
            rootCTM = .scale(userMM, userMM)
            viewport = ((wMM ?? 100 * userMM) / userMM, (hMM ?? 100 * userMM) / userMM)
        }
        let unitScale = ImportGeometry.maxStretch(rootCTM)

        var builder = SVGGeometryBuilder(tolerance: tol, ids: tree.ids)
        builder.inkscapeLayers = SVGGeometryBuilder.hasInkscapeLayers(root)
        builder.renderChildren(of: root, SVGState(ctm: rootCTM, viewport: viewport))

        let (chained, layers) = PathChainer.chainByLayer(builder.closed + builder.open, layers: builder.closedLayers + builder.openLayers,
                                                         tolerance: PathChainer.joinTolerance(for: tol))
        warnings.append(contentsOf: builder.warningMessages())
        if chained.duplicatesRemoved > 0 {
            warnings.append("Removed \(chained.duplicatesRemoved) duplicate path\(chained.duplicatesRemoved == 1 ? "" : "s") " +
                "(drawn more than once on top of each other).")
        }
        if chained.openCount > 0 {
            warnings.append("\(chained.openCount) open path\(chained.openCount == 1 ? "" : "s") left open " +
                "(endpoints do not meet within \(PathChainer.joinTolerance(for: tol)) mm).")
        }
        if chained.polylines.isEmpty {
            warnings.append("No supported geometry found in the SVG file.")
        }

        // SVG is Y-down: flip about the document height (or the drawing's own extent when unknown).
        let flipHeight = hMM ?? chained.polylines.bounds.max.y
        let flip = Transform2D(a: 1, b: 0, c: 0, d: -1, tx: 0, ty: flipHeight.isFinite ? flipHeight : 0)
        return ImportResult(polylines: chained.polylines.map { $0.transformed(flip) }, points: [], warnings: warnings,
                            sourceUnits: sourceUnits, unitScale: unitScale, polylineLayers: layers)
    }
}

// MARK: - XML tree

final class SVGElement {
    let name: String
    let attributes: [String: String]
    var children: [SVGElement] = []

    init(name: String, attributes: [String: String]) {
        self.name = name
        self.attributes = attributes
    }

    subscript(_ key: String) -> String? { attributes[key] }

    /// Value of a presentation property from the `style` attribute, falling back to the attribute itself.
    func property(_ key: String) -> String? {
        if let style = attributes["style"] {
            for decl in style.split(separator: ";") {
                let parts = decl.split(separator: ":", maxSplits: 1)
                if parts.count == 2, parts[0].trimmingCharacters(in: .whitespaces) == key {
                    return parts[1].replacingOccurrences(of: "!important", with: "").trimmingCharacters(in: .whitespaces)
                }
            }
        }
        return attributes[key]?.trimmingCharacters(in: .whitespaces)
    }

    var href: String? { attributes["href"] ?? attributes["xlink:href"] }
}

final class SVGTreeBuilder: NSObject, XMLParserDelegate {
    private(set) var root: SVGElement?
    private(set) var comments: [String] = []
    private(set) var ids: [String: SVGElement] = [:]
    /// Set when the XML was only partly readable (the elements before the error are kept).
    private(set) var partialParseError: String?
    private var stack: [SVGElement] = []

    static func parse(_ data: Data) throws -> SVGTreeBuilder {
        let builder = SVGTreeBuilder()
        let parser = XMLParser(data: data)
        parser.shouldProcessNamespaces = false
        parser.shouldResolveExternalEntities = false
        parser.delegate = builder
        let ok = parser.parse()
        if !ok {
            let reason = parser.parserError?.localizedDescription ?? "unknown XML error"
            let message = "invalid XML at line \(parser.lineNumber): \(reason)"
            if builder.root == nil { throw VectorImportError.malformed(message) }
            builder.partialParseError = message
        }
        return builder
    }

    func parser(_ parser: XMLParser, didStartElement elementName: String, namespaceURI: String?,
                qualifiedName qName: String?, attributes attributeDict: [String: String] = [:]) {
        let name = elementName.hasPrefix("svg:") ? String(elementName.dropFirst(4)) : elementName
        let el = SVGElement(name: name, attributes: attributeDict)
        if let id = attributeDict["id"], ids[id] == nil { ids[id] = el }
        if let parent = stack.last {
            parent.children.append(el)
        } else if root == nil {
            root = el
        }
        stack.append(el)
    }

    func parser(_ parser: XMLParser, didEndElement elementName: String, namespaceURI: String?, qualifiedName qName: String?) {
        _ = stack.popLast()
    }

    func parser(_ parser: XMLParser, foundComment comment: String) {
        comments.append(comment)
    }
}

// MARK: - Attribute parsing

struct SVGLength {
    var value: Double
    var unit: String

    static func parse(_ s: String?) -> SVGLength? {
        guard let s else { return nil }
        let t = s.trimmingCharacters(in: .whitespacesAndNewlines)
        var scanner = SVGNumberScanner(t)
        guard let v = scanner.number() else { return nil }
        let unit = String(decoding: scanner.bytes[scanner.index...], as: UTF8.self).trimmingCharacters(in: .whitespaces).lowercased()
        return SVGLength(value: v, unit: unit)
    }

    /// CSS pixels per unit (1in = 96px).
    static func cssPixels(_ unit: String) -> Double {
        switch unit {
        case "in": 96
        case "cm": 96 / 2.54
        case "mm": 96 / 25.4
        case "q": 96 / 101.6
        case "pt": 96.0 / 72
        case "pc": 16
        case "em": 16
        case "ex": 8
        default: 1
        }
    }

    enum Axis { case x, y, other }

    /// Length in user units; percentages resolve against the viewport.
    static func userUnits(_ s: String?, _ axis: Axis, viewport: (w: Double, h: Double)) -> Double? {
        guard let l = parse(s) else { return nil }
        if l.unit == "%" {
            let ref: Double
            switch axis {
            case .x: ref = viewport.w
            case .y: ref = viewport.h
            case .other: ref = ((viewport.w * viewport.w + viewport.h * viewport.h) / 2).squareRoot()
            }
            return l.value / 100 * ref
        }
        return l.value * cssPixels(l.unit)
    }
}

struct SVGViewBox {
    var x: Double, y: Double, w: Double, h: Double

    static func parse(_ s: String?) -> SVGViewBox? {
        guard let s else { return nil }
        let n = SVGNumber.list(s)
        guard n.count == 4, n[2] > 0, n[3] > 0 else { return nil }
        return SVGViewBox(x: n[0], y: n[1], w: n[2], h: n[3])
    }

    /// Maps viewBox coordinates onto a viewport of `width` × `height` (SVG `preserveAspectRatio` rules).
    func transform(toWidth width: Double, height: Double, preserveAspectRatio par: String?) -> Transform2D {
        let sx = width / w, sy = height / h
        let words = (par ?? "").split(whereSeparator: { $0 == " " || $0 == "," }).map(String.init).filter { $0 != "defer" }
        let align = words.first ?? "xMidYMid"
        let toOrigin = Transform2D.translation(Vec2(-x, -y))
        if align == "none" { return toOrigin.then(.scale(sx, sy)) }
        let slice = words.count > 1 && words[1] == "slice"
        let s = slice ? max(sx, sy) : min(sx, sy)
        let alignX: Double = align.hasPrefix("xMin") ? 0 : align.hasPrefix("xMax") ? 1 : 0.5
        let alignY: Double = align.hasSuffix("YMin") ? 0 : align.hasSuffix("YMax") ? 1 : 0.5
        let tx = (width - w * s) * alignX, ty = (height - h * s) * alignY
        return toOrigin.then(.scale(s, s)).then(.translation(Vec2(tx, ty)))
    }
}

enum SVGNumber {
    /// All numbers in a whitespace/comma separated list (stops at the first non-number).
    static func list(_ s: String) -> [Double] {
        var scanner = SVGNumberScanner(s)
        var out: [Double] = []
        while let v = scanner.number() { out.append(v) }
        return out
    }

    static func format(_ v: Double) -> String {
        v == v.rounded() ? String(Int(v)) : String(v)
    }

    /// Parses an SVG transform list. Returns nil if it is malformed.
    static func transform(_ s: String) -> Transform2D? {
        var scanner = SVGNumberScanner(s)
        var result = Transform2D.identity
        while true {
            scanner.skipSeparators()
            guard !scanner.atEnd else { return result }
            guard let name = scanner.identifier() else { return nil }
            scanner.skipWhitespace()
            guard scanner.consume(UInt8(ascii: "(")) else { return nil }
            var args: [Double] = []
            while let v = scanner.number() { args.append(v) }
            scanner.skipWhitespace()
            guard scanner.consume(UInt8(ascii: ")")) else { return nil }
            let t: Transform2D
            switch (name, args.count) {
            case ("matrix", 6):
                t = Transform2D(a: args[0], b: args[1], c: args[2], d: args[3], tx: args[4], ty: args[5])
            case ("translate", 1): t = .translation(Vec2(args[0], 0))
            case ("translate", 2): t = .translation(Vec2(args[0], args[1]))
            case ("scale", 1): t = .scale(args[0], args[0])
            case ("scale", 2): t = .scale(args[0], args[1])
            case ("rotate", 1): t = .rotation(args[0].radians)
            case ("rotate", 3):
                let c = Vec2(args[1], args[2])
                t = Transform2D.translation(-c).then(.rotation(args[0].radians)).then(.translation(c))
            case ("skewX", 1): t = Transform2D(a: 1, b: 0, c: tan(args[0].radians), d: 1, tx: 0, ty: 0)
            case ("skewY", 1): t = Transform2D(a: 1, b: tan(args[0].radians), c: 0, d: 1, tx: 0, ty: 0)
            default: return nil
            }
            // "A B" means apply B first, then A.
            result = t.then(result)
        }
    }
}

/// Byte scanner for SVG number lists, path data and transform lists.
struct SVGNumberScanner {
    let bytes: [UInt8]
    var index = 0

    init(_ s: String) { bytes = Array(s.utf8) }

    var atEnd: Bool { index >= bytes.count }
    var peek: UInt8? { index < bytes.count ? bytes[index] : nil }

    static func isSpace(_ c: UInt8) -> Bool { c == 0x20 || c == 0x09 || c == 0x0A || c == 0x0D || c == 0x0C }
    static func isDigit(_ c: UInt8) -> Bool { c >= 0x30 && c <= 0x39 }
    static func isLetter(_ c: UInt8) -> Bool { (c >= 0x41 && c <= 0x5A) || (c >= 0x61 && c <= 0x7A) }

    mutating func skipWhitespace() { while let c = peek, Self.isSpace(c) { index += 1 } }

    /// Skips whitespace and at most one comma.
    mutating func skipSeparators() {
        skipWhitespace()
        if peek == UInt8(ascii: ",") { index += 1; skipWhitespace() }
    }

    mutating func consume(_ c: UInt8) -> Bool {
        if peek == c { index += 1; return true }
        return false
    }

    mutating func identifier() -> String? {
        let start = index
        while let c = peek, Self.isLetter(c) { index += 1 }
        return index > start ? String(decoding: bytes[start..<index], as: UTF8.self) : nil
    }

    /// Next number (after optional separators), per the SVG number grammar: `-.5.5` is two numbers.
    mutating func number() -> Double? {
        let save = index
        skipSeparators()
        let start = index
        if let c = peek, c == UInt8(ascii: "+") || c == UInt8(ascii: "-") { index += 1 }
        var digits = 0
        while let c = peek, Self.isDigit(c) { index += 1; digits += 1 }
        if peek == UInt8(ascii: ".") {
            index += 1
            while let c = peek, Self.isDigit(c) { index += 1; digits += 1 }
        }
        guard digits > 0 else { index = save; return nil }
        if let c = peek, c == UInt8(ascii: "e") || c == UInt8(ascii: "E") {
            var k = index + 1
            if k < bytes.count, bytes[k] == UInt8(ascii: "+") || bytes[k] == UInt8(ascii: "-") { k += 1 }
            if k < bytes.count, Self.isDigit(bytes[k]) {
                index = k
                while let c = peek, Self.isDigit(c) { index += 1 }
            }
        }
        guard let v = Double(String(decoding: bytes[start..<index], as: UTF8.self)), v.isFinite else {
            index = save
            return nil
        }
        return v
    }

    /// A single-character arc flag (`0` or `1`), which needs no separator after it.
    mutating func flag() -> Bool? {
        let save = index
        skipSeparators()
        switch peek {
        case UInt8(ascii: "0"): index += 1; return false
        case UInt8(ascii: "1"): index += 1; return true
        default: index = save; return nil
        }
    }
}

// MARK: - Path data

/// Receives path segments in user units and flattens them into device (mm, Y-down) polylines.
struct SVGPathSink {
    let ctm: Transform2D
    let tolerance: Double
    let localTolerance: Double
    var subpaths: [Polyline] = []
    private var current: [Vec2] = []

    init(ctm: Transform2D, tolerance: Double) {
        self.ctm = ctm
        self.tolerance = tolerance
        self.localTolerance = ImportGeometry.localTolerance(tolerance, for: ctm)
    }

    mutating func moveTo(_ p: Vec2) {
        flush(closed: false)
        current = [ctm.apply(p)]
    }

    mutating func lineTo(_ p: Vec2) { current.append(ctm.apply(p)) }

    mutating func cubic(_ p0: Vec2, _ c1: Vec2, _ c2: Vec2, _ p1: Vec2) {
        let start = current.last ?? ctm.apply(p0)
        Curves.flattenCubic(start, ctm.apply(c1), ctm.apply(c2), ctm.apply(p1), tolerance: tolerance, into: &current)
    }

    mutating func quad(_ p0: Vec2, _ c: Vec2, _ p1: Vec2) {
        let start = current.last ?? ctm.apply(p0)
        Curves.flattenQuad(start, ctm.apply(c), ctm.apply(p1), tolerance: tolerance, into: &current)
    }

    mutating func arc(_ p0: Vec2, _ p1: Vec2, rx: Double, ry: Double, rotation: Double, largeArc: Bool, sweep: Bool) {
        var local: [Vec2] = []
        Curves.flattenEllipticalArc(from: p0, to: p1, rx: rx, ry: ry, xAxisRotation: rotation, largeArc: largeArc,
                                    sweep: sweep, tolerance: localTolerance, into: &local)
        current.append(contentsOf: local.map(ctm.apply))
    }

    /// Adds already-sampled local points as one subpath.
    mutating func polygon(_ pts: [Vec2], closed: Bool) {
        flush(closed: false)
        current = pts.map(ctm.apply)
        flush(closed: closed)
    }

    mutating func close() { flush(closed: true) }

    mutating func finish() { flush(closed: false) }

    private mutating func flush(closed: Bool) {
        defer { current = [] }
        guard current.count >= 2 else { return }
        let poly = Polyline(current, closed: closed).deduplicated(tolerance: 1e-9)
        guard poly.count >= 2 else { return }
        subpaths.append(poly.count >= 3 ? poly : Polyline(poly.points, closed: false))
    }
}

enum SVGPathParser {
    /// Parses `d` into `sink`. Returns an error description if the data is malformed (everything up to
    /// the bad command has already been drawn, as the SVG spec requires).
    static func parse(_ d: String, into sink: inout SVGPathSink) -> String? {
        var s = SVGNumberScanner(d)
        var cur = Vec2.zero, start = Vec2.zero
        var lastCubic: Vec2?, lastQuad: Vec2?
        var command: UInt8?
        var needsMove = false
        var error: String?

        func began() {
            if needsMove { sink.moveTo(start); needsMove = false }
        }

        loop: while true {
            s.skipSeparators()
            guard let c = s.peek else { break }
            if SVGNumberScanner.isLetter(c) {
                if command == nil, c != UInt8(ascii: "M"), c != UInt8(ascii: "m") {
                    error = "path data must begin with a moveto"
                    break
                }
                s.index += 1
                command = c
            } else if let prev = command, prev != UInt8(ascii: "z"), prev != UInt8(ascii: "Z") {
                // Implicit repetition; extra moveto pairs are lineto.
                if prev == UInt8(ascii: "M") { command = UInt8(ascii: "L") }
                if prev == UInt8(ascii: "m") { command = UInt8(ascii: "l") }
            } else {
                error = "unexpected “\(Character(UnicodeScalar(c)))” at offset \(s.index)"
                break
            }
            guard let cmd = command else { break }
            let rel = cmd >= UInt8(ascii: "a")
            let base = rel ? cur : Vec2.zero
            func pt() -> Vec2? {
                guard let x = s.number(), let y = s.number() else { return nil }
                return Vec2(x, y) + base
            }
            let upper = rel ? cmd - 32 : cmd
            var nextCubic: Vec2?, nextQuad: Vec2?
            switch upper {
            case UInt8(ascii: "M"):
                guard let p = pt() else { error = "bad moveto"; break loop }
                sink.moveTo(p)
                cur = p; start = p; needsMove = false
            case UInt8(ascii: "L"):
                guard let p = pt() else { error = "bad lineto"; break loop }
                began(); sink.lineTo(p); cur = p
            case UInt8(ascii: "H"):
                guard let x = s.number() else { error = "bad horizontal lineto"; break loop }
                let p = Vec2(rel ? cur.x + x : x, cur.y)
                began(); sink.lineTo(p); cur = p
            case UInt8(ascii: "V"):
                guard let y = s.number() else { error = "bad vertical lineto"; break loop }
                let p = Vec2(cur.x, rel ? cur.y + y : y)
                began(); sink.lineTo(p); cur = p
            case UInt8(ascii: "C"):
                guard let c1 = pt(), let c2 = pt(), let p = pt() else { error = "bad curveto"; break loop }
                began(); sink.cubic(cur, c1, c2, p); nextCubic = c2; cur = p
            case UInt8(ascii: "S"):
                guard let c2 = pt(), let p = pt() else { error = "bad smooth curveto"; break loop }
                let c1 = lastCubic.map { cur * 2 - $0 } ?? cur
                began(); sink.cubic(cur, c1, c2, p); nextCubic = c2; cur = p
            case UInt8(ascii: "Q"):
                guard let c1 = pt(), let p = pt() else { error = "bad quadratic curveto"; break loop }
                began(); sink.quad(cur, c1, p); nextQuad = c1; cur = p
            case UInt8(ascii: "T"):
                guard let p = pt() else { error = "bad smooth quadratic curveto"; break loop }
                let c1 = lastQuad.map { cur * 2 - $0 } ?? cur
                began(); sink.quad(cur, c1, p); nextQuad = c1; cur = p
            case UInt8(ascii: "A"):
                guard let rx = s.number(), let ry = s.number(), let rot = s.number(),
                      let large = s.flag(), let sweep = s.flag(), let p = pt() else {
                    error = "bad elliptical arc"; break loop
                }
                began()
                if rx == 0 || ry == 0 {
                    sink.lineTo(p)
                } else {
                    sink.arc(cur, p, rx: rx, ry: ry, rotation: rot, largeArc: large, sweep: sweep)
                }
                cur = p
            case UInt8(ascii: "Z"):
                sink.close()
                cur = start
                needsMove = true
            default:
                error = "unknown command “\(Character(UnicodeScalar(cmd)))”"
                break loop
            }
            lastCubic = nextCubic
            lastQuad = nextQuad
        }
        sink.finish()
        return error
    }
}

// MARK: - Rendering

struct SVGState {
    /// User units → mm (still Y-down).
    var ctm: Transform2D
    /// Current viewport size in user units (for percentage lengths).
    var viewport: (w: Double, h: Double)
    /// The layer being drawn (see `SVGGeometryBuilder.layerName`), nil outside any.
    var layer: String? = nil
    /// How many groups deep: 0 for the root's own children.
    var depth = 0
}

struct SVGGeometryBuilder {
    let tolerance: Double
    let ids: [String: SVGElement]
    var closed: [Polyline] = []
    var open: [Polyline] = []
    /// The layer of each closed and open path.
    var closedLayers: [String?] = []
    var openLayers: [String?] = []
    /// True when the file has Inkscape layers: then only they count as layers.
    var inkscapeLayers = false
    private var skipped: [String: Int] = [:]
    private var notes: [String] = []
    private var noteSet: Set<String> = []
    private var useStack: [ObjectIdentifier] = []

    init(tolerance: Double, ids: [String: SVGElement]) {
        self.tolerance = tolerance
        self.ids = ids
    }

    private mutating func note(_ s: String) {
        if noteSet.insert(s).inserted { notes.append(s) }
    }

    func warningMessages() -> [String] {
        var out = notes
        for (name, count) in skipped.sorted(by: { $0.key < $1.key }) {
            var msg = "Skipped \(count) <\(name)> element\(count == 1 ? "" : "s") (not supported)"
            if name == "text" { msg += "; convert text to paths (outlines) before exporting" }
            if name == "image" { msg += "; raster images cannot be machined as vectors" }
            out.append(msg + ".")
        }
        return out
    }

    private static let nonRendering: Set<String> = [
        "defs", "clipPath", "mask", "symbol", "marker", "pattern", "linearGradient", "radialGradient",
        "filter", "style", "script", "metadata", "title", "desc", "font", "font-face", "glyph", "missing-glyph",
        "cursor", "view", "animate", "animateMotion", "animateTransform", "set", "mpath", "solidColor",
    ]

    static func hasInkscapeLayers(_ el: SVGElement) -> Bool {
        el["inkscape:groupmode"] == "layer" || el.children.contains { hasInkscapeLayers($0) }
    }

    /// The layer a `<g>` starts, if it starts one: an Inkscape layer (its label), or, in a file without them, a group
    /// straight under the root with a name, as Illustrator (`data-name`, else `id`), Affinity (`serif:id`) and most
    /// other drawing programs write their layers. Inkscape's own automatic group ids (`g123`) don't name a layer.
    func layerName(_ el: SVGElement, _ state: SVGState) -> String? {
        func clean(_ s: String?) -> String? {
            guard let t = s?.trimmingCharacters(in: .whitespaces), !t.isEmpty else { return nil }
            return t
        }
        if inkscapeLayers {
            guard el["inkscape:groupmode"] == "layer" else { return nil }
            return clean(el["inkscape:label"]) ?? clean(el["id"])
        }
        guard state.depth == 0 else { return nil }
        if let name = clean(el["data-name"]) ?? clean(el["serif:id"]) { return name }
        guard let id = clean(el["id"]), id.range(of: #"^g\d+$"#, options: .regularExpression) == nil else { return nil }
        return id
    }

    private static func isHidden(_ el: SVGElement) -> Bool {
        el.property("display") == "none"
    }

    private mutating func elementTransform(_ el: SVGElement) -> Transform2D {
        guard let s = el["transform"], !s.trimmingCharacters(in: .whitespaces).isEmpty else { return .identity }
        if let t = SVGNumber.transform(s) { return t }
        note("Ignored an invalid transform “\(s)”.")
        return .identity
    }

    mutating func renderChildren(of el: SVGElement, _ state: SVGState) {
        if el.name == "switch" {
            // Render the first direct child that would render (conditional attributes are not evaluated).
            if let first = el.children.first(where: { !Self.nonRendering.contains($0.name) && !Self.isHidden($0) }) {
                render(first, state)
            }
            return
        }
        for child in el.children { render(child, state) }
    }

    mutating func render(_ el: SVGElement, _ state: SVGState) {
        guard !Self.isHidden(el) else { return }
        if Self.nonRendering.contains(el.name) { return }
        var s = state
        switch el.name {
        case "g", "a", "switch":
            s.ctm = elementTransform(el).then(state.ctm)
            if el.name == "g", let name = layerName(el, state) { s.layer = name }
            s.depth = state.depth + 1
            renderChildren(of: el, s)
        case "svg":
            renderNestedSVG(el, state, transform: elementTransform(el).then(state.ctm), size: nil)
        case "use":
            renderUse(el, state)
        case "path", "rect", "circle", "ellipse", "line", "polyline", "polygon":
            s.ctm = elementTransform(el).then(state.ctm)
            renderShape(el, s)
        case "text", "image", "foreignObject", "video", "audio", "iframe", "canvas":
            skipped[el.name == "foreignObject" ? "foreignObject" : el.name, default: 0] += 1
        default:
            // Unknown or foreign-namespace elements (sodipodi:namedview, ...) are ignored.
            break
        }
    }

    private mutating func renderNestedSVG(_ el: SVGElement, _ state: SVGState, transform: Transform2D,
                                          size: (w: Double?, h: Double?)?) {
        let x = SVGLength.userUnits(el["x"], .x, viewport: state.viewport) ?? 0
        let y = SVGLength.userUnits(el["y"], .y, viewport: state.viewport) ?? 0
        let w = size?.w ?? SVGLength.userUnits(el["width"], .x, viewport: state.viewport) ?? state.viewport.w
        let h = size?.h ?? SVGLength.userUnits(el["height"], .y, viewport: state.viewport) ?? state.viewport.h
        guard w > 0, h > 0 else { return }
        var s = state
        let place = Transform2D.translation(Vec2(x, y)).then(transform)
        if let vb = SVGViewBox.parse(el["viewBox"]) {
            s.ctm = vb.transform(toWidth: w, height: h, preserveAspectRatio: el["preserveAspectRatio"]).then(place)
            s.viewport = (vb.w, vb.h)
        } else {
            s.ctm = place
            s.viewport = (w, h)
        }
        renderChildren(of: el, s)
    }

    private mutating func renderUse(_ el: SVGElement, _ state: SVGState) {
        guard let ref = el.href, ref.hasPrefix("#") else {
            if let ref = el.href { note("Skipped <use> of external reference “\(ref)”.") }
            return
        }
        let id = String(ref.dropFirst())
        guard let target = ids[id] else {
            note("Skipped <use> of missing element “#\(id)”.")
            return
        }
        let key = ObjectIdentifier(target)
        guard useStack.count < 32, !useStack.contains(key) else {
            note("Skipped a <use> that references itself.")
            return
        }
        guard !Self.isHidden(target) else { return }
        useStack.append(key)
        defer { useStack.removeLast() }
        let x = SVGLength.userUnits(el["x"], .x, viewport: state.viewport) ?? 0
        let y = SVGLength.userUnits(el["y"], .y, viewport: state.viewport) ?? 0
        let base = Transform2D.translation(Vec2(x, y)).then(elementTransform(el)).then(state.ctm)
        switch target.name {
        case "symbol", "svg":
            // The use's width/height (default 100%) size the symbol's viewport.
            let w = SVGLength.userUnits(el["width"], .x, viewport: state.viewport)
            let h = SVGLength.userUnits(el["height"], .y, viewport: state.viewport)
            renderNestedSVG(target, state, transform: (target.name == "svg" ? elementTransform(target) : .identity).then(base),
                            size: (w, h))
        default:
            if Self.nonRendering.contains(target.name) {
                note("Skipped <use> of a non-rendering <\(target.name)>.")
                return
            }
            var s = state
            s.ctm = base
            // `render` applies the target's own transform.
            render(target, s)
        }
    }

    private mutating func renderShape(_ el: SVGElement, _ state: SVGState) {
        var sink = SVGPathSink(ctm: state.ctm, tolerance: tolerance)
        let vp = state.viewport
        func len(_ key: String, _ axis: SVGLength.Axis) -> Double? { SVGLength.userUnits(el[key], axis, viewport: vp) }
        switch el.name {
        case "path":
            guard let d = el["d"], d.trimmingCharacters(in: .whitespacesAndNewlines) != "none" else { return }
            if let err = SVGPathParser.parse(d, into: &sink) {
                note("Path data error (\(err)); the path was drawn up to the error.")
            }
        case "rect":
            let x = len("x", .x) ?? 0, y = len("y", .y) ?? 0
            guard let w = len("width", .x), let h = len("height", .y), w > 0, h > 0 else { return }
            var rx = len("rx", .x), ry = len("ry", .y)
            if rx == nil || (rx ?? 0) < 0 { rx = (ry ?? 0) >= 0 ? ry : nil }
            if ry == nil || (ry ?? 0) < 0 { ry = rx }
            let rxv = min(max(rx ?? 0, 0), w / 2), ryv = min(max(ry ?? 0, 0), h / 2)
            if rxv <= 0 || ryv <= 0 {
                sink.polygon([Vec2(x, y), Vec2(x + w, y), Vec2(x + w, y + h), Vec2(x, y + h)], closed: true)
            } else {
                sink.moveTo(Vec2(x + rxv, y))
                sink.lineTo(Vec2(x + w - rxv, y))
                sink.arc(Vec2(x + w - rxv, y), Vec2(x + w, y + ryv), rx: rxv, ry: ryv, rotation: 0, largeArc: false, sweep: true)
                sink.lineTo(Vec2(x + w, y + h - ryv))
                sink.arc(Vec2(x + w, y + h - ryv), Vec2(x + w - rxv, y + h), rx: rxv, ry: ryv, rotation: 0, largeArc: false, sweep: true)
                sink.lineTo(Vec2(x + rxv, y + h))
                sink.arc(Vec2(x + rxv, y + h), Vec2(x, y + h - ryv), rx: rxv, ry: ryv, rotation: 0, largeArc: false, sweep: true)
                sink.lineTo(Vec2(x, y + ryv))
                sink.arc(Vec2(x, y + ryv), Vec2(x + rxv, y), rx: rxv, ry: ryv, rotation: 0, largeArc: false, sweep: true)
                sink.close()
            }
        case "circle":
            let c = Vec2(len("cx", .x) ?? 0, len("cy", .y) ?? 0)
            guard let r = len("r", .other), r > 0 else { return }
            sink.polygon(Curves.circle(center: c, radius: r, tolerance: sink.localTolerance), closed: true)
        case "ellipse":
            let c = Vec2(len("cx", .x) ?? 0, len("cy", .y) ?? 0)
            var rx = len("rx", .x), ry = len("ry", .y)
            if rx == nil { rx = ry }
            if ry == nil { ry = rx }
            guard let rxv = rx, let ryv = ry, rxv > 0, ryv > 0 else { return }
            var pts = ImportGeometry.ellipseArc(center: c, u: Vec2(rxv, 0), v: Vec2(0, ryv), start: 0, sweep: 2 * .pi,
                                                tolerance: sink.localTolerance)
            pts.removeLast()
            sink.polygon(pts, closed: true)
        case "line":
            let a = Vec2(len("x1", .x) ?? 0, len("y1", .y) ?? 0)
            let b = Vec2(len("x2", .x) ?? 0, len("y2", .y) ?? 0)
            sink.polygon([a, b], closed: false)
        case "polyline", "polygon":
            let n = SVGNumber.list(el["points"] ?? "")
            let pts = stride(from: 0, to: n.count - 1, by: 2).map { Vec2(n[$0], n[$0 + 1]) }
            if n.count % 2 == 1 { note("A <\(el.name)> had an odd number of coordinates; the last one was ignored.") }
            sink.polygon(pts, closed: el.name == "polygon")
        default:
            return
        }
        sink.finish()
        for p in sink.subpaths {
            if p.isClosed {
                closed.append(p)
                closedLayers.append(state.layer)
            } else {
                open.append(p)
                openLayers.append(state.layer)
            }
        }
    }
